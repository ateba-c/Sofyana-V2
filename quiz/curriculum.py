def ref_string(slug, limit=120):
    """'QC-033, QC-113' — fits Skill.curriculum_ref (max 120 chars)."""
    out = ''
    for n in sorted(set(CURRICULUM_REFS.get(slug, []))):
        part = f'QC-{n:03d}'
        nxt = f'{out}, {part}' if out else part
        if len(nxt) > limit:
            break
        out = nxt
    return out
