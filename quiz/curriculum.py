    """'QC-033, QC-113' — fits Skill.curriculum_ref (max 120 chars)."""
    out = ''
    for n in CURRICULUM_REFS.get(slug, []):
        part = f'QC-{n:03d}'
        nxt = f'{out}, {part}' if out else part
        if len(nxt) > limit:
            break
        out = nxt
    return out
